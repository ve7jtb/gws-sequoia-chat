// Emit the public algorithm lists used by the browser's SSH transport check.
package main

import (
	"encoding/json"
	"fmt"
	"os"

	"golang.org/x/crypto/ssh"
)

func main() {
	// Connect uses the library defaults. Populate the transport probe from
	// the same dependency so an upgrade cannot silently change its prediction.
	var config ssh.Config
	config.SetDefaults()
	offer := struct {
		KeyExchanges []string `json:"keyExchanges"`
		Ciphers      []string `json:"ciphers"`
		MACs         []string `json:"macs"`
		HostKeys     []string `json:"hostKeys"`
	}{
		config.KeyExchanges, config.Ciphers, config.MACs,
		// Used only to solicit a proposal. The probe does not predict or
		// approve server authentication.
		ssh.SupportedAlgorithms().HostKeys,
	}
	fmt.Print("// Generated by ssh-engine/cmd/probe-offer.\nexport default ")
	out := json.NewEncoder(os.Stdout)
	out.SetIndent("", " ")
	if err := out.Encode(offer); err != nil {
		panic(err)
	}
}
